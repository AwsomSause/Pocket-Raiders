// Builds src/ui/pocket/pocket.gen.css from the Pokémon-style UI mock-ups (plans/ui-redesign/src/pNN.css), so the game
// draws its Pocket pages with the mock-ups' own rules.   node tools/build-pocket-css.mjs
//
// The mock-up page turns each pass's rules on and off with the pass slider. The game shows Kice's picks instead:
// Title at pass 17, Pause at pass 24, the main game at the Final Cut (26), the new areas at the Master Cut (51).
// So the rules are grouped into four tiers; a view carries the tier classes its page needs (src/ui/pocket/kit.ts).
// `:where()` keeps every rule's weight the same as in the mock-ups, where all of them sat under `#stage`.
// Keyframes get the `pk-` prefix (the New UI has its own `spin`), and pictures become CSS variables that
// src/ui/pocket/art.ts fills in with the game's own files.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const SRC = 'plans/ui-redesign/src/';
const OUT = 'src/ui/pocket/pocket.gen.css';
const LAST = 51;
/** Tier a pass belongs to: the first pick that includes it. */
const tierOf = (n) => (n <= 17 ? 17 : n <= 24 ? 24 : n <= 26 ? 26 : 51);

const nested = { 17: [], 24: [], 26: [], 51: [] };
const tops = [];
for (let n = 1; n <= LAST; n++) {
  const f = `${SRC}p${String(n).padStart(2, '0')}.css`;
  if (!existsSync(f)) continue;
  const css = readFileSync(f, 'utf8');
  const cut = css.indexOf('/*@top*/');
  nested[tierOf(n)].push(`/* pass ${n} */\n${(cut < 0 ? css : css.slice(0, cut)).trim()}`);
  if (cut >= 0) tops.push(css.slice(cut + 8).trim());
}

const top = tops.join('\n');
const names = [...top.matchAll(/@keyframes\s+([\w-]+)/g)].map((m) => m[1]);
const nameRe = new RegExp(`(?<![\\w-])(${[...new Set(names)].sort((a, b) => b.length - a.length).join('|')})(?![\\w-])`, 'g');
const pics = new Set();
const fix = (css) => css
  .replace(/(animation(?:-name)?\s*:)([^;{}]+)/g, (_, p, v) => p + v.replace(nameRe, 'pk-$1'))
  .replace(/url\((['"]?)sprites\/([\w-]+)\.png\1\)/g, (_, _q, key) => { pics.add(key); return `var(--pk-u-${key})`; });

const out = ['/* GENERATED by tools/build-pocket-css.mjs from plans/ui-redesign/src/pNN.css. Do not edit: change the source or pocket.css. */'];
for (const t of [17, 24, 26, 51]) out.push(`.pkx .pks${t === 17 ? '' : `:where(.t${t})`}{\n${fix(nested[t].join('\n'))}\n}`);
// Top-level rules: keyframes are kept (renamed); the mock-up viewer's own page-change rules are re-made in pocket.css.
const keyframes = [...top.matchAll(/@keyframes\s+([\w-]+)\s*\{((?:[^{}]|\{[^{}]*\})*)\}/g)].map((m) => `@keyframes pk-${m[1]}{${fix(m[2].trim())}}`);
out.push(keyframes.join('\n'));
if (keyframes.length !== names.length) throw new Error(`keyframes read ${keyframes.length} of ${names.length}`);

writeFileSync(OUT, out.join('\n') + '\n');
console.log(`${OUT}: ${Math.round(out.join('\n').length / 1024)} KB, ${keyframes.length} keyframes, ${pics.size} pictures: ${[...pics].sort().join(' ')}`);
