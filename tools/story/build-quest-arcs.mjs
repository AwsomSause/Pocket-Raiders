// Builds the quest arcs that unlock Rare and Exceptional Remembrance lines from tools/story/quest-arcs.tsv.
// Writes src/data/story/questArcs.json (src/data/story/questArcs.ts expands it into events and arcs) and
// src/data/story/text/questArcs.en.json, and points each unlocked line's `unlock` at its arc's last scene.
// Run: node tools/story/build-quest-arcs.mjs, then npm run data:story.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const rows = readFileSync(new URL('tools/story/quest-arcs.tsv', root), 'utf8').split('\n').filter((l) => l.trim() && !l.startsWith('#')).map((l) => l.split('|').map((s) => s.trim()));
const remPath = new URL('src/data/story/remembrances.json', root);
const rems = JSON.parse(readFileSync(remPath, 'utf8'));
const byId = new Map(rems.map((r) => [r.id, r]));
const arcs = [];
const text = {};
for (const r of rows) {
  if (r.length !== 5) throw new Error(`bad row (${r.length} fields): ${r[0]}`);
  const [id, unlocks, act, b1, b2] = r;
  if (!/^[a-z][a-z0-9_]*$/.test(id)) throw new Error(`bad arc id ${id}`);
  let arc = arcs.find((a) => a.id === id);
  if (!arc) arcs.push((arc = { id, unlocks: unlocks.split(','), acts: [] }));
  for (const u of arc.unlocks) if (!byId.has(u)) throw new Error(`${id}: unknown Remembrance ${u}`);
  const n = arc.acts.length + 1;
  if (n > 1 && Number(act) < arc.acts[n - 2]) throw new Error(`${id}: acts must not go down`);
  arc.acts.push(Number(act));
  text[`qa.${id}.${n}.b1`] = b1;
  text[`qa.${id}.${n}.b2`] = b2;
}
for (const a of arcs) {
  if (a.acts.length < 2) throw new Error(`${a.id}: a quest arc needs 2 or more scenes`);
  for (const u of a.unlocks) byId.get(u).unlock = { kind: 'event', arg: `ev_qa_${a.id}_${a.acts.length}` };
}
const unlocked = new Set(arcs.flatMap((a) => a.unlocks));
// Every Rare and Exceptional line needs a way in: a quest arc here, or a backstory event that unlocks it.
const backstoryUnlocks = new Set(JSON.parse(readFileSync(new URL('src/data/story/arcs.json', root), 'utf8')).flatMap((a) => (a.effects ?? []).filter((e) => e.kind === 'unlock').map((e) => e.target)));
const events = JSON.parse(readFileSync(new URL('src/data/story/events.json', root), 'utf8'));
for (const e of events) for (const f of [...(e.outputs ?? []), ...(e.choices ?? []).flatMap((c) => c.effects ?? [])]) if (f.kind === 'unlock') backstoryUnlocks.add(f.target);
const missing = rems.filter((r) => (r.rarity === 'rare' || r.rarity === 'exceptional') && !unlocked.has(r.id) && !backstoryUnlocks.has(r.id)).map((r) => r.id);
if (missing.length) throw new Error(`no unlock route for ${missing.join(', ')}`);
writeFileSync(new URL('src/data/story/questArcs.json', root), JSON.stringify({ note: 'Generated by node tools/story/build-quest-arcs.mjs from tools/story/quest-arcs.tsv. Quest arcs unlocking Rare and Exceptional Remembrance lines; expanded by src/data/story/questArcs.ts.', arcs }) + '\n');
writeFileSync(new URL('src/data/story/text/questArcs.en.json', root), JSON.stringify(text, null, 1) + '\n');
writeFileSync(remPath, JSON.stringify(rems, null, 1) + '\n');
console.log(`quest arcs: ${arcs.length} arcs, ${rows.length} scenes, unlocking ${unlocked.size} lines`);
