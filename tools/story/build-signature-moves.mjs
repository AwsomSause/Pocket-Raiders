// Builds src/data/storySignatureMoves.json from tools/story/signature-roster.tsv: Signature I, Signature II and the
// Keystone upgrade of Signature I for each of the 74 Remembrance lines (Design v2 Part II and II-D).
// The moves carry the `storysig` flag, so no learnset, random-move rule or Metronome-style pool picks them up.
// Keystone rule (Part II-D): change exactly one thing. Plain attacks get about +15% power (to the nearest 5, at most
// 105); otherwise a chance rises 15 points, a heal or drain rises about 15%, a stat change goes one stage further,
// or (shields, field moves) PP rises from 5 to 8. Also gives each move the animation of the strongest ordinary move
// of its type and category (presentation only). Run: node tools/story/build-signature-moves.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const rows = readFileSync(new URL('tools/story/signature-roster.tsv', root), 'utf8').split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split('|'));
const lines = new Set(read('src/data/story/remembrances.json').map((r) => r.line[0]));
const idOf = (name) => `sig-${name.toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
const FOE = (fx) => Boolean(fx.status || fx.confuse || fx.randomStatus || fx.trap || fx.stageTrick || fx.statChanges?.some((c) => c.target === 'enemy'));

function build([line, slot, name, type, cat, power, acc, priority, crit, effects, flags]) {
  const fx = JSON.parse(effects);
  const status = cat === 'St';
  return {
    id: idOf(name), name, type,
    category: status ? 'status' : cat === 'P' ? 'physical' : 'special',
    power: status ? null : Number(power),
    accuracy: acc === '-' ? null : Number(acc),
    pp: 5, priority: Number(priority), critStage: Number(crit),
    target: status && !FOE(fx) ? 'self' : 'enemy',
    flags: ['storysig', ...flags.split(',').filter(Boolean)],
    effects: fx,
    line, slot: Number(slot),
  };
}

function keystone(m) {
  const k = structuredClone(m);
  k.id = `${m.id}-keystone`;
  k.name = `${m.name}+`;
  k.slot = 3;
  const fx = k.effects;
  const plain = m.power !== null && !fx.powerRule && !fx.hits && !fx.doubleBelowHalf && !fx.charge;
  const chance = fx.status ?? fx.confuse ?? (fx.flinchChance !== undefined ? null : undefined);
  if (plain && m.power < 105) k.power = Math.min(105, Math.round((m.power * 1.15) / 5) * 5);
  else if (chance && chance.chance < 100) chance.chance = Math.min(100, chance.chance + 15);
  else if (fx.flinchChance !== undefined && fx.flinchChance < 100) fx.flinchChance = Math.min(100, fx.flinchChance + 15);
  else if (fx.statChanges?.some((c) => c.chance < 100)) { const c = fx.statChanges.find((x) => x.chance < 100); c.chance = Math.min(100, c.chance + 15); }
  else if (fx.heal) fx.heal = Math.min(1, Math.round(fx.heal * 1.15 * 100) / 100);
  else if (fx.drain) fx.drain = Math.min(1, Math.round(fx.drain * 1.15 * 100) / 100);
  else if (fx.statChanges?.length) { const c = fx.statChanges[0]; c.stages = c.stages > 0 ? Math.min(3, c.stages + 1) : Math.max(-3, c.stages - 1); }
  else if (m.power !== null && m.power < 105 && !fx.hits) k.power = Math.min(105, Math.round((m.power * 1.15) / 5) * 5);
  else k.pp = 8;
  return k;
}

const sig = rows.map(build);
const byLine = {};
for (const m of sig) {
  if (!lines.has(m.line)) throw new Error(`${m.name}: unknown line ${m.line}`);
  byLine[m.line] ??= {};
  byLine[m.line][m.slot === 1 ? 'sig1' : 'sig2'] = m.id;
}
const keys = sig.filter((m) => m.slot === 1).map(keystone);
for (const k of keys) byLine[k.line].keystone = k.id;
for (const l of lines) if (!byLine[l]?.sig1 || !byLine[l]?.sig2) throw new Error(`line ${l} is missing a signature move`);
const all = [...sig, ...keys];
if (new Set(all.map((m) => m.id)).size !== all.length) throw new Error('duplicate signature move id');
const moves = all.map(({ line: _l, slot: _s, ...m }) => m);
// One game-style description per move (shown in the move details, like the Mega signature moves).
const title = (id) => id.split(/[-_]/).map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
const sig1Name = Object.fromEntries(sig.filter((m) => m.slot === 1).map((m) => [m.id, m.name]));
const descriptions = Object.fromEntries(all.map((m) => [m.id, m.id.endsWith('-keystone')
  ? `${sig1Name[m.id.slice(0, -'-keystone'.length)]} grown stronger by the Keystone Memory. Only ${title(m.line)}'s line knows it.`
  : m.slot === 1
    ? `A move only ${title(m.line)}'s line and its Trainer share, first found in a hard-won fight.`
    : `${title(m.line)}'s line's second own move, born from the story the two of you lived.`]));
writeFileSync(new URL('src/data/storySignatureMoves.json', root), JSON.stringify({ note: 'Generated by node tools/story/build-signature-moves.mjs from tools/story/signature-roster.tsv. Story Run signature moves (Sig I, Sig II, Keystone) for the 74 Remembrance lines; flag storysig.', byLine, descriptions, moves }, null, 1) + '\n');
console.log(`story signature moves: ${moves.length} (${Object.keys(byLine).length} lines)`);

const ordinary = read('src/data/moves.json');
const animsPath = new URL('src/data/moveAnims.json', root);
const anims = JSON.parse(readFileSync(animsPath, 'utf8'));
for (const m of moves) {
  const donor = ordinary.filter((o) => o.type === m.type && o.category === m.category && anims.moves[o.id] && !/^(z|max)-/.test(o.id)).sort((a, b) => (b.power ?? 0) - (a.power ?? 0) || a.id.localeCompare(b.id))[0];
  if (!donor) throw new Error(`no animation donor for ${m.id}`);
  const { pack: _p, script: _s, ...look } = anims.moves[donor.id];
  anims.moves[m.id] = { ...look, source: 'type' };
}
writeFileSync(animsPath, JSON.stringify(anims, null, 2) + '\n');
