// Builds the Story Run Starter arcs (one 3-beat arc per Remembrance line, `arc_rm_<line>`) from tools/story/starter-arcs.tsv.
// Writes src/data/story/starterArcs.json (the line list; src/data/story/starterArcs.ts expands it into events and an arc)
// and src/data/story/text/starterArcs.en.json (the lines). Run: node tools/story/build-starter-arcs.mjs, then npm run data:story.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const rows = readFileSync(new URL('tools/story/starter-arcs.tsv', root), 'utf8').split('\n').filter((l) => l.trim() && !l.startsWith('#')).map((l) => l.split('|'));
const rems = JSON.parse(readFileSync(new URL('src/data/story/remembrances.json', root), 'utf8'));
const ids = new Set(rems.map((r) => r.id));
const text = {
  'sa.choice.together': 'Stand beside it.',
  'sa.choice.trust': 'Trust it to face this on its own.',
};
const lines = [];
for (const r of rows) {
  if (r.length !== 6) throw new Error(`bad row (${r.length} fields): ${r[0]}`);
  const [line, name, place, struggle, turning, answer] = r.map((s) => s.trim());
  if (!ids.has(`rm_${line}`)) throw new Error(`unknown line ${line}`);
  if (lines.includes(line)) throw new Error(`duplicate line ${line}`);
  lines.push(line);
  Object.assign(text, {
    [`sa.${line}.1.b1`]: `At ${place}, ${name} slows down. Something here has its full attention.`,
    [`sa.${line}.1.b2`]: struggle,
    [`sa.${line}.2.b1`]: turning,
    [`sa.${line}.2.b2`]: `${name} looks back at you, waiting to see what you will do.`,
    [`sa.${line}.3.b1`]: answer,
    [`sa.${line}.3.b2`]: `Something settles between you and ${name}. Whatever comes next, it has its own way of meeting it.`,
  });
}
const missing = [...ids].filter((id) => !lines.includes(id.replace(/^rm_/, '')));
if (missing.length) throw new Error(`no Starter arc for ${missing.join(', ')}`);
writeFileSync(new URL('src/data/story/starterArcs.json', root), JSON.stringify({ note: 'Generated by node tools/story/build-starter-arcs.mjs from tools/story/starter-arcs.tsv. One Starter arc per Remembrance line; expanded by src/data/story/starterArcs.ts.', lines }) + '\n');
writeFileSync(new URL('src/data/story/text/starterArcs.en.json', root), JSON.stringify(text, null, 1) + '\n');
console.log(`starter arcs: ${lines.length} lines, ${Object.keys(text).length} text lines`);
