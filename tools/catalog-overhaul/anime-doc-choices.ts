// Reads the anime questline docs of the Catalog Overhaul Pack and writes the choice labels each questline must offer
// (tests/unit/fixtures/coAnimeChoices.json). The unit test tests/unit/coAnime.test.ts checks the built events against it:
// an automated part of the "re-read the doc" rule. Run: node tools/catalog-overhaul/anime-doc-choices.ts [pack folder]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const pack = process.argv[2] ?? '/mnt/project-files/catalog_overhaul_pack/catalog_overhaul';
const out = join(import.meta.dirname, '../../tests/unit/fixtures/coAnimeChoices.json');
// The deepened docs replace the short scripts, so they are read last and their labels are added to the short script's.
const DOCS: [string, RegExp][] = [
  ['QUESTLINES_ANIME_INSPIRED.md', /^## (AN\d+)\. /],
  ['QUESTLINES_ASH.md', /^## (AQ\d+)\. /],
  ['QUESTLINES_DEEPENED_1.md', /^## (AN\d+)\. /],
  ['QUESTLINES_DEEPENED_2.md', /^## (AQ\d+)\. /],
];
const labels: Record<string, string[]> = {};
const titles: Record<string, string> = {};
for (const [file, heading] of DOCS) {
  let q: string | null = null;
  for (const raw of readFileSync(join(pack, file), 'utf8').split('\n')) {
    if (raw.startsWith('## ')) {
      const m = heading.exec(raw);
      q = m ? m[1]! : null;
      if (q) titles[q] ??= raw.replace(/^## \w+\. /, '').replace(/ \(.*\)$/, '').trim();
      continue;
    }
    // "**Choices.** "A" / "B"", "**Choices (first meeting).** ...", "> **Choices:** ...", "**Answers.** ..."
    if (!q || !/\*\*(Choices|Answers)[^*]*\*\*/.test(raw)) continue;
    const line = raw.replace(/\*\([^)]*\)\*/g, '');
    for (const m of line.matchAll(/"([^"]+)"/g)) {
      const label = m[1]!.trim();
      (labels[q] ??= []).includes(label) || labels[q]!.push(label);
    }
  }
}
const order = (a: string, b: string) => a.slice(0, 2).localeCompare(b.slice(0, 2)) || Number(a.slice(2)) - Number(b.slice(2));
const questlines = Object.fromEntries(Object.keys(titles).sort(order).map((q) => [q, { title: titles[q], choices: labels[q] ?? [] }]));
writeFileSync(out, JSON.stringify({ note: 'Generated by tools/catalog-overhaul/anime-doc-choices.ts from the pack docs. Do not edit by hand.', questlines }, null, 1) + '\n');
console.log(`${Object.keys(questlines).length} questlines, ${Object.values(labels).reduce((n, l) => n + l.length, 0)} choice labels`);
