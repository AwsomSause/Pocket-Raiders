// Catalog Overhaul, people: rebuilds src/data/catalogOverhaul/flags/people.json from every tools/events/co/people-*.ts module.
// A module may export AFTERSTORY ({ match, readBy }[]: flags it sets that another system reads) and EXTERNAL (string[]: flags it reads
// that another category sets). Run: node tools/catalog-overhaul/people-flags.ts
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '../..');
const dir = join(root, 'tools/events/co');
const afterstory: { match: string; readBy: string }[] = [
  { match: 'roster-[a-z-]+-(done|m2)', readBy: 'The next meeting (m2), and the All-Star Tournament and Final Reunion (done): ROAD_ROSTER.md, How the Roster runs' },
  { match: 'lore-[a-z-]+', readBy: 'Lore fragments (src/data/npcStory.json lore; the lore book reads lore-<id>)' },
  { match: 'rep', readBy: '"Reputation +1" (STANDARDS.md pack words): a run flag until the per-region reputation system reads it' },
];
const external = new Set<string>();
for (const f of readdirSync(dir).filter((n) => n.startsWith('people-') && n.endsWith('.ts')).sort()) {
  try {
    const mod = (await import(join(dir, f))) as { AFTERSTORY?: { match: string; readBy: string }[]; EXTERNAL?: string[] };
    for (const a of mod.AFTERSTORY ?? []) if (!afterstory.some((b) => b.match === a.match)) afterstory.push(a);
    for (const k of mod.EXTERNAL ?? []) external.add(k);
  } catch (err) {
    console.warn(`skipped ${f}: ${(err as Error).message.split('\n')[0]}`);
  }
}
const out = {
  category: 'people',
  note: 'Generated by tools/catalog-overhaul/people-flags.ts from the AFTERSTORY and EXTERNAL exports of tools/events/co/people-*.ts. `external`: flags this category reads that another category sets. `afterstory`: flags this category sets whose reader is another system (the Final Reunion, the All-Star Tournament, a Gym battle); `match` is a regular expression over the whole key.',
  external: [...external].sort(),
  afterstory,
};
writeFileSync(join(root, 'src/data/catalogOverhaul/flags/people.json'), JSON.stringify(out, null, 1) + '\n');
console.log(`flags/people.json: ${external.size} external, ${afterstory.length} afterstory`);
