// Builds src/ui/phantom/phantom.gen.css from the Phantom UI mock-ups (plans/ui-redesign-persona/src/css), so the game
// wears the same rules the mock-ups were approved with. Run: node tools/build-phantom-css.mjs
// What it changes: drops the mock-up viewer's own rules, scopes everything under .phx (the game's Phantom layer),
// turns the pass classes (.p1 ... .p25) into the stage class .phs (the game always shows the final pass), and gives
// every @keyframes a ph- name so none collides with the game's own.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const SRC = 'plans/ui-redesign-persona/src/css';
const OUT = 'src/ui/phantom/phantom.gen.css';
const raw = readdirSync(SRC).filter((f) => f.endsWith('.css')).sort().map((f) => readFileSync(`${SRC}/${f}`, 'utf8')).join('\n').replace(/\/\*[\s\S]*?\*\//g, '');

/** Top-level blocks: [selector or at-rule, body]. */
const blocks = [];
let depth = 0, head = '', start = 0;
for (let i = 0, from = 0; i < raw.length; i++) {
  const ch = raw[i];
  if (ch === '{') { if (depth === 0) { head = raw.slice(from, i).trim(); start = i + 1; } depth++; }
  else if (ch === '}') { depth--; if (depth === 0) { blocks.push([head, raw.slice(start, i)]); from = i + 1; } }
}

const names = blocks.filter(([h]) => h.startsWith('@keyframes')).map(([h]) => h.split(/\s+/)[1]);
const nameRe = new RegExp(`(?<![\\w-])(${[...new Set(names)].sort((a, b) => b.length - a.length).join('|')})(?![\\w-])`, 'g');
const body = (b) => b
  .replace(/(animation(?:-name)?\s*:)([^;{}]+)/g, (_, p, v) => p + v.replace(nameRe, 'ph-$1'))
  .replace(/(--an\s*:)([^;{}]+)/g, (_, p, v) => p + v.replace(nameRe, 'ph-$1'))
  .replace(/url\(sprites\/map-region0\.png\)/g, 'var(--ph-map0)')
  .replace(/\s*\n\s*/g, '');
const DROP = /^(\.vw|body|@media \(max-width|::view-transition|html\[data-tr|#stage)/;
const sel = (s) => s.split(',').map((one) => '.phx ' + one.trim().replace(/\.stage\b/g, '.phs').replace(/\.p\d+(?![\w-])/g, '.phs')).join(',');

const out = [];
for (const [h, b] of blocks) {
  if (DROP.test(h)) continue;
  if (h.startsWith('@keyframes')) out.push(`@keyframes ph-${h.split(/\s+/)[1]}{${body(b)}}`);
  else if (h === ':root') out.push(`.phx{${b.split(';').map((d) => d.trim()).filter((d) => d.startsWith('--') && !d.startsWith('--vw-')).join(';')}}`);
  else if (h.startsWith('@media')) out.push(`${h}{${body(b).replace(/\.stage\b/g, '.phx .phs')}}`);
  else out.push(`${sel(h)}{${body(b)}}`);
}
const nested = out.join('\n').match(/[\s{};]\.p\d+[\s.[{:,]/g);
if (nested) console.warn('pass classes left inside rules:', nested.length, nested.slice(0, 5));
writeFileSync(OUT, `/* GENERATED by tools/build-phantom-css.mjs from plans/ui-redesign-persona/src/css. Do not edit: change the source or phantom.css. */\n${out.join('\n')}\n`);
console.log(`${OUT}: ${out.length} rules, ${Math.round(out.join('\n').length / 1024)} KB, ${names.length} keyframes, names: ${[...new Set(names)].filter((n) => n.length < 4).join(' ')}`);
