#!/usr/bin/env python3
"""Ports the Dominion 50-pass redesign CSS (plans/evil-mode-rework/redesign-50/src/pNN.css) into the game.

Every pass's CSS is kept in pass order (the mockups are cumulative), nested under `#rx #r5` (the id of the root of a redesigned
Dominion screen; the id outranks the New look skins). Keyframes get an `r5-` prefix, and every animation's delay runs
on the page clock (`var(--now)`, set by the r50 kit) so a redraw (a cursor move) doesn't restart it, while opening a new
page plays its entrances once. Sprite urls point at public/assets/images/dominion/r50/ (copied from the mockups' sprites folder).

Run: python3 tools/dominion/port-r50.py   (writes src/ui/redux/screens/dominion/r50/r50.css)
Never edit r50.css by hand: fix the mockup or this tool, then run it again.
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'plans/evil-mode-rework/redesign-50/src')
DST = os.path.join(ROOT, 'src/ui/redux/screens/dominion/r50/r50.css')
LAST = 50
TIME = re.compile(r'^-?[\d.]+m?s$')
NOW = 'var(--now,0ms)'


def split_top(text, sep=','):
    """Split on `sep` outside parentheses."""
    out, depth, cur = [], 0, ''
    for ch in text:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return out


def tokens(item):
    out, depth, cur = [], 0, ''
    for ch in item.strip():
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch.isspace() and depth == 0:
            if cur:
                out.append(cur)
            cur = ''
        else:
            cur += ch
    if cur:
        out.append(cur)
    return out


def is_time(t):
    return bool(TIME.match(t)) or t.startswith('var(--') or t.startswith('calc(')


def shorthand(value, names):
    items = []
    for item in split_top(value):
        toks = tokens(item)
        if not toks or toks[0] in ('none', 'inherit', 'initial', 'unset'):
            items.append(item.strip())
            continue
        toks = ['r5-' + t if t in names else t for t in toks]
        times = [i for i, t in enumerate(toks) if is_time(t)]
        if len(times) >= 2:
            toks[times[1]] = 'calc(%s + %s)' % (NOW, toks[times[1]])
        elif len(times) == 1:
            toks.insert(times[0] + 1, NOW)
        items.append(' '.join(toks))
    return ','.join(items)


def delays(value):
    return ','.join('calc(%s + %s)' % (NOW, v.strip()) for v in split_top(value))


def rewrite(css, names):
    def anim(m):
        prop, val, end = m.group(1), m.group(2), m.group(3)
        imp = ''
        if val.rstrip().endswith('!important'):
            val, imp = val.rstrip()[:-10], '!important'
        if prop == 'animation':
            val = shorthand(val, names)
        elif prop == 'animation-name':
            val = ','.join('r5-' + v.strip() if v.strip() in names else v.strip() for v in val.split(','))
        elif prop == 'animation-delay':
            val = delays(val)
        return '%s:%s%s%s' % (prop, val, imp, end)
    css = re.sub(r'(?<![\w-])(animation(?:-name|-delay)?)\s*:\s*([^;}]+)([;}])', anim, css)
    css = re.sub(r'url\((["\']?)sprites/', r'url(\1/assets/images/dominion/r50/', css)
    return css


def main():
    parts = []
    for n in range(1, LAST + 1):
        p = os.path.join(SRC, 'p%02d.css' % n)
        if os.path.exists(p):
            nested, _, top = open(p, encoding='utf8').read().partition('/*@top*/')
            parts.append((n, re.sub(r'/\*.*?\*/', '', nested, flags=re.S), re.sub(r'/\*.*?\*/', '', top, flags=re.S)))
    names = set()
    for _, nested, top in parts:
        names.update(re.findall(r'@keyframes\s+([\w-]+)', nested + top))
    out = ['/* GENERATED by tools/dominion/port-r50.py from plans/evil-mode-rework/redesign-50 (passes 1-%d). Do not edit. */' % LAST,
           # The game's other style sheets (.rx .keys, .rx .row, .rx .tabs...) share class names with the mockups:
           # every element inside a redesigned page starts from the browser's defaults, as it did in the mockups.
           '#rx #r5 *,#rx #r5 *::before,#rx #r5 *::after{all:revert}',
           '#rx #r5{position:absolute;left:0;top:0;width:960px;height:540px;overflow:hidden;contain:layout paint}',
           '#rx #r5,#rx #r5 *,#rx #r5 *::before,#rx #r5 *::after{box-sizing:border-box}',
           '#rx #r5 img{max-width:none;display:block;user-select:none}',
           '#rx #r5 .px{image-rendering:pixelated}',
           '#rx #r5 [data-go],#rx #r5 [data-act]{cursor:pointer}',
           '#rx.calm #r5 *,#rx.calm #r5 *::before,#rx.calm #r5 *::after{animation:none!important;transition:none!important}',
           '@media (prefers-reduced-motion:reduce){#rx #r5 *,#rx #r5 *::before,#rx #r5 *::after{animation:none!important;transition:none!important}}',
           '#rx #r5{']
    tops = []
    for n, nested, top in parts:
        out.append('/* pass %d */' % n)
        out.append(rewrite(nested.strip(), names))
        top = re.sub(r'@keyframes\s+([\w-]+)', lambda m: '@keyframes r5-' + m.group(1), top)
        tops.append(rewrite(top.strip(), names))
    out.append('}')
    out.extend(t for t in tops if t)
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    open(DST, 'w', encoding='utf8').write('\n'.join(out) + '\n')
    sizes = {}
    from PIL import Image
    sd = os.path.join(ROOT, 'public/assets/images/dominion/r50')
    for f in sorted(os.listdir(sd)):
        if f.endswith('.png'):
            sizes[f[:-4]] = list(Image.open(os.path.join(sd, f)).size)
    ts = '// GENERATED by tools/dominion/port-r50.py: pixel size [w, h] of every sprite in public/assets/images/dominion/r50/.\n'
    ts += 'export const R5_SIZES: Readonly<Record<string, readonly [number, number]>> = {\n'
    ts += ''.join('  %s: [%d, %d],\n' % (json.dumps(k), w, h) for k, (w, h) in sizes.items()) + '};\n'
    open(os.path.join(os.path.dirname(DST), 'sizes.ts'), 'w', encoding='utf8').write(ts)
    print('wrote %s (%d KB, %d keyframes)' % (os.path.relpath(DST, ROOT), os.path.getsize(DST) // 1024, len(names)))


main()
