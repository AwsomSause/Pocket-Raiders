"""Ports the DOMINION mockup CSS (plans/evil-mode-rework/mockups-v3/index.html (round 3; earlier: mockups-redesign)) into the game.

Every selector is scoped under `#rx .dom` (the id outranks the New look skins' class rules) (the root of a Dominion screen), keyframes get a `dm-` prefix, the page layout
(header, figures, captions) is dropped, and looping animations take the view's clock (`var(--now)`) so a redraw
doesn't restart them. Run: python3 tools/dominion/port-mockup-css.py <mockup index.html> src/ui/redux/screens/dominion/dominion.css
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
html = open(src, encoding='utf-8').read()
css = html[html.index('<style>') + 7:html.index('</style>')]
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)

DROP = ('body', '.wrap', 'a', ':focus-visible', '.mast', 'figure', 'figcaption', '.frame', '.passes', 'header', '.wrap>header')
TIME = re.compile(r'^-?[\d.]+m?s$')


def split_rules(text):
    """Top-level blocks: (prelude, body)."""
    out, i, depth, start = [], 0, 0, 0
    pre = ''
    while i < len(text):
        ch = text[i]
        if ch == '{':
            if depth == 0:
                pre = text[start:i].strip()
                body_start = i + 1
            depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0:
                out.append((pre, text[body_start:i]))
                start = i + 1
        i += 1
    return out


def anim(decls):
    def fix(m):
        parts = []
        for one in re.split(r',(?![^()]*\))', m.group(2)):
            toks = one.split()
            if toks and not toks[0][0].isdigit() and toks[0] not in ('none', 'var(--now)'):
                toks[0] = 'dm-' + toks[0]
            times = [k for k, t in enumerate(toks) if TIME.match(t)]
            if len(times) == 1 and 'infinite' in toks:
                toks.insert(times[0] + 1, 'var(--now,0s)')
            parts.append(' '.join(toks))
        return m.group(1) + ','.join(parts)
    decls = re.sub(r'(animation:)([^;!}]+)', fix, decls)
    # A delay set on its own still runs on the view's clock, so a redraw doesn't restart it (a one-shot entrance
    # plays once when the view opens).
    decls = re.sub(r'(animation-delay:)\s*([^;!}]+)', lambda m: m.group(1) + 'calc(var(--now,0s) + %s)' % m.group(2).strip(), decls)
    return re.sub(r'(animation-name:)\s*([\w-]+)', lambda m: m.group(1) + 'dm-' + m.group(2), decls)


def scope(sel):
    outs = []
    for s in sel.split(','):
        s = s.strip()
        if s in (':root', 'html'):
            outs.append('#rx .dom')
        elif s == '*':
            outs.append('#rx .dom *')
        else:
            outs.append('#rx .dom ' + s)
    return ','.join(outs)


def keep(sel):
    first = [s.strip() for s in sel.split(',')]
    return not all(s.split(' ')[0].split(':')[0] in DROP or s.startswith(DROP) and not s.startswith('.a') for s in first)


def emit(rules, inner=False):
    lines = []
    for pre, body in rules:
        if pre.startswith('@keyframes'):
            name = pre.split()[1]
            lines.append('@keyframes dm-%s{%s}' % (name, body.strip()))
        elif pre.startswith('@property'):
            lines.append('%s{%s}' % (pre, body.strip()))
        elif pre.startswith('@media'):
            if 'max-width' in pre:
                continue
            lines.append('%s{\n%s\n}' % (pre, emit(split_rules(body), True)))
        else:
            if not keep(pre):
                continue
            lines.append('%s{%s}' % (scope(pre), anim(body.strip())))
    return '\n'.join(lines)


out = '/* Generated by tools/dominion/port-mockup-css.py from the DOMINION mockups. Edit the tool or add rules at the end, under the marker. */\n'
out += emit(split_rules(css)) + '\n'
# The New look skins style some of the same class names (redux.css); undo what the mockups don't set themselves.
out += '''#rx .dom .hd{position:static;left:auto;right:auto;top:auto;height:auto;padding:0 0 7px;background:none;color:inherit;z-index:auto;text-shadow:none;white-space:normal;clip-path:none;min-width:0;border-radius:0}
#rx .dom .mt{display:block;width:auto;pointer-events:auto;animation:none}
#rx .dom .sm{opacity:1}
#rx .dom .col{gap:0}
#rx .dom .key{width:auto;height:auto;display:inline-block;color:inherit;font-weight:400}
'''
# Mockup sprites the CSS points at live in public/assets/images/dominion/ in the game (Vite adds the base path).
out = re.sub(r'url\((["\']?)sprites/', r'url(\1/assets/images/dominion/', out)
open(dst, 'w', encoding='utf-8').write(out)
print(len(out), 'bytes')
