// Writes src/data/catalogOverhaul/flags/families-a.json from the built co-families-a-*.json files:
// every remembered flag, the events that set it and the events that read it. Run: node tools/events/co/_fa-flags.ts
// NOTES explains flags that cross a category border (set here for another family to read, or read here from one).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Json = Record<string, unknown>;
const root = join(import.meta.dirname, '../../..');
const dir = join(root, 'src/data/events');
export const NOTES: Record<string, string> = JSON.parse(readFileSync(join(import.meta.dirname, '_fa-flag-notes.json'), 'utf8')) as Record<string, string>;

export function collect(): Record<string, { setBy: string[]; readBy: string[]; note?: string }> {
  const flags: Record<string, { setBy: Set<string>; readBy: Set<string> }> = {};
  const at = (k: string) => (flags[k] ??= { setBy: new Set(), readBy: new Set() });
  const walk = (x: unknown, id: string): void => {
    if (Array.isArray(x)) return x.forEach((y) => walk(y, id));
    if (!x || typeof x !== 'object') return;
    const o = x as Json;
    if ((o.kind === 'flag' || o.kind === 'flagAge') && typeof o.key === 'string') {
      if (o.kind === 'flag' && 'amount' in o) { if (Number(o.amount) > 0) at(o.key).setBy.add(id); } else at(o.key).readBy.add(id);
    }
    Object.values(o).forEach((y) => walk(y, id));
  };
  for (const f of readdirSync(dir).filter((n) => n.startsWith('co-families-a-')).sort()) {
    for (const e of (JSON.parse(readFileSync(join(dir, f), 'utf8')) as { events: Json[] }).events) walk(e, String(e.id));
  }
  // A note is only kept where it is needed: a flag nothing here reads, or nothing here sets. A key in NOTES may use * as a wildcard.
  const patterns = Object.keys(NOTES).filter((k) => k.includes('*')).map((k) => ({ re: new RegExp(`^${k.replace(/\*/g, '.*')}$`), note: NOTES[k]! }));
  const noteOf = (k: string): string | undefined => NOTES[k] ?? patterns.find((p) => p.re.test(k))?.note;
  return Object.fromEntries(Object.keys(flags).sort().map((k) => {
    const f = flags[k]!;
    const note = f.setBy.size === 0 || f.readBy.size === 0 ? noteOf(k) : undefined;
    return [k, { setBy: [...f.setBy].sort(), readBy: [...f.readBy].sort(), ...(note ? { note } : {}) }];
  }));
}

// The file form other rows use: a list of { key, setBy, readBy, note? }. A flag nothing here sets is a `hook` (its note names the writer).
export function asList(flags: ReturnType<typeof collect>): { key: string; setBy: string[]; readBy: string[]; note?: string; hook?: string }[] {
  return Object.entries(flags).map(([key, f]) => ({ key, ...f, ...(f.setBy.length === 0 && f.note ? { hook: f.note } : {}) }));
}

if (process.argv[1]?.endsWith('_fa-flags.ts')) {
  const flags = asList(collect());
  writeFileSync(join(root, 'src/data/catalogOverhaul/flags/families-a.json'), JSON.stringify({ category: 'families-a', note: 'Generated by tools/events/co/_fa-flags.ts. Run flags (same run only). A flag with no reader here carries a note saying who reads it.', flags }, null, 1) + '\n');
  console.log(`${flags.length} flags`);
}
