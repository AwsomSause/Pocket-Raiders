# Copies the Hub Town mini-map, districts and place doors out of the game's data into src/js/05-data-hub.js, so the mock-up town map is the real town.
import json
from pathlib import Path
R = Path(__file__).resolve().parent.parent; G = R.parent.parent
h = json.load(open(G / 'src/data/hubTown.json'))
out = {'map': h['minimap'], 'districts': [[d['id'], d['name'], d['rect'], d['color'], d['blurb']] for d in h['districts']],
       'places': [[p['id'], p['name'], p['door']['x'], p['door']['y'], p['blurb']] for p in h['places']], 'spawn': [h['spawn']['x'], h['spawn']['y']]}
(R / 'src/js/05-data-hub.js').write_text('/* Generated by src/hubdata.py from src/data/hubTown.json. Do not edit by hand. */\nconst HUB=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('hub data', len(out['places']), 'places')
